// Builds the result tables of the README from the committed files under results/. Nothing in the tables is typed by hand.
//   node dist/scripts/render-tables.js           rewrite the marked region of README.md and results/TABLES.md
//   node dist/scripts/render-tables.js --check   fail if either file differs from what the result files give
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isMain, repoRoot } from './paths.js';

export const START = '<!-- results:start (generated by scripts/render-tables.ts from results/*.json; do not edit by hand) -->';
export const END = '<!-- results:end -->';

interface Stats {
  mean: number;
  sd: number;
  min: number;
  max: number;
  median: number;
}

interface Meta {
  commit: string;
  dirty: boolean;
  node: string;
  os: string;
  cpu: string;
  logicalCpus: number;
  totalRamGb: number;
}

const pct = (x: number, digits = 1) => `${(x * 100).toFixed(digits)}%`;
const range = (s: Stats, f: (x: number) => string) => (s.min === s.max ? f(s.mean) : `${f(s.mean)} (${f(s.min)} to ${f(s.max)})`);
const short = (m: Meta) => m.commit.slice(0, 7);
const n0 = (x: number) => x.toLocaleString('en-US', { maximumFractionDigits: 0 });

function read<T>(root: string, rel: string): T {
  return JSON.parse(readFileSync(join(root, rel), 'utf8')) as T;
}

interface CoverageFile {
  seeds: number[];
  trialsPerSeed: number;
  monteCarloSePerSeed: number;
  settings: Array<{
    id: string;
    label: string;
    users: number;
    trueRatio: number;
    summary: { naive: Stats; clustered: Stats; naiveMeanWidth: number; clusteredMeanWidth: number };
  }>;
  meta: Meta;
}

function coverageTable(root: string): string {
  const f = read<CoverageFile>(root, 'results/coverage/coverage.json');
  const rows = f.settings.map(
    (s) =>
      `| ${s.label} | ${s.users} | ${s.trueRatio.toFixed(3)} | ${range(s.summary.naive, pct)} | ${range(s.summary.clustered, pct)} | ${s.summary.naiveMeanWidth.toFixed(4)} | ${s.summary.clusteredMeanWidth.toFixed(4)} |`,
  );
  return [
    '### Coverage of the 95% interval when requests are correlated within a user',
    '',
    `Each setting is ${f.trialsPerSeed.toLocaleString('en-US')} simulated experiments per seed, ${f.seeds.length} seeds (${f.seeds[0]} to ${f.seeds[f.seeds.length - 1]}). A cell is the mean over seeds of the share of intervals that contain the true ratio, with the lowest and highest seed in brackets. One seed of ${f.trialsPerSeed.toLocaleString('en-US')} experiments has a Monte Carlo standard error of about ${(f.monteCarloSePerSeed * 100).toFixed(2)} percentage points at 95%.`,
    '',
    '| setting | users | true ratio | request-level interval | user-level interval (delta method) | mean width, request-level | mean width, user-level |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    `Source: \`results/coverage/coverage.json\`, run at commit \`${short(f.meta)}\`.`,
  ].join('\n');
}

interface FaultFile {
  seeds: number[];
  faultsPerFamilyPerSeed: number;
  stream: {
    usersPerStream: number;
    cleanBaseline: Array<{ seed: number; events: number; findings: number }>;
    families: Array<{ id: string; description: string; expectation: string; note: string; injected: number; detected: number; stray: number; rate: Stats }>;
    highCardinality: { description: string; perSeed: Array<{ injected: number; detected: number; falsePositives: number }> };
  };
  code: {
    callsPerCorpus: number;
    cleanBaseline: Array<{ seed: number; calls: number; findings: number }>;
    families: Array<{ id: string; description: string; expectation: string; note: string; injected: number; exact: number; unverifiable: number; missed: number; stray: number; exactRate: Stats }>;
  };
  meta: Meta;
}

function faultTables(root: string): string {
  const f = read<FaultFile>(root, 'results/fault-injection/fault-injection.json');
  const streamRows = f.stream.families.map(
    (r) => `| ${r.id} | ${r.description} | ${r.injected} | ${r.detected} | ${range(r.rate, pct)} | ${r.stray} | ${r.note === '' ? '' : r.note} |`,
  );
  const codeRows = f.code.families.map(
    (r) => `| ${r.id} | ${r.description} | ${r.injected} | ${r.exact} | ${r.unverifiable} | ${r.missed} | ${r.stray} | ${r.note === '' ? '' : r.note} |`,
  );
  const hc = f.stream.highCardinality.perSeed;
  const hcInjected = hc.reduce((a, s) => a + s.injected, 0);
  const hcDetected = hc.reduce((a, s) => a + s.detected, 0);
  const hcFalse = hc.reduce((a, s) => a + s.falsePositives, 0);
  const streamEvents = f.stream.cleanBaseline.map((b) => b.events);
  const streamFindings = f.stream.cleanBaseline.reduce((a, b) => a + b.findings, 0);
  const codeFindings = f.code.cleanBaseline.reduce((a, b) => a + b.findings, 0);
  const codeCalls = f.code.cleanBaseline.reduce((a, b) => a + b.calls, 0);
  return [
    '### Fault injection: streams',
    '',
    `Each row injects ${f.faultsPerFamilyPerSeed} faults of one kind into a clean synthetic stream (${f.stream.usersPerStream.toLocaleString('en-US')} users, ${n0(Math.min(...streamEvents))} to ${n0(Math.max(...streamEvents))} events), once for each of ${f.seeds.length} seeds. A fault counts as detected when the tool reports the expected finding at the injected line (for the funnel rows, for the injected user). Rate is the mean over seeds with the lowest and highest seed in brackets. "Stray" counts findings that match no injected fault.`,
    '',
    '| fault | what was injected | injected (all seeds) | detected | rate | stray | why it is missed |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...streamRows,
    '',
    `High cardinality: ${f.stream.highCardinality.description}. Detected in ${hcDetected} of ${hcInjected} streams; flagged in ${hcFalse} of ${hcInjected} control streams.`,
    '',
    `Controls: the clean streams gave ${streamFindings} findings in total across ${f.stream.cleanBaseline.length} seeds.`,
    '',
    '### Fault injection: source code',
    '',
    `Each row injects ${f.faultsPerFamilyPerSeed} faults of one kind into a synthetic corpus of ${f.code.callsPerCorpus} tracker calls (the other ${f.faultsPerFamilyPerSeed} calls stay clean), once for each of ${f.seeds.length} seeds. "Located" means the expected finding at the injected line. "Unverifiable" means the tool did not name the fault but reported the call as one it could not check, which still fails the run. "Missed" means no finding at all. "Stray" counts findings outside the injected calls.`,
    '',
    '| fault | what was injected | injected (all seeds) | located | unverifiable | missed | stray | why it is not located |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...codeRows,
    '',
    `Controls: ${codeCalls.toLocaleString('en-US')} clean calls across ${f.code.cleanBaseline.length} seeds gave ${codeFindings} findings.`,
    '',
    `Source: \`results/fault-injection/fault-injection.json\`, run at commit \`${short(f.meta)}\`.`,
  ].join('\n');
}

interface RuntimeFile {
  events: number;
  users: number;
  fileBytes: number;
  runs: Array<{ run: number; wallMs: number; checkMs: number; peakRssMb: number; eventsPerSecond: number; findings: number; freeRamGbBefore: number }>;
  summary: { wallMs: Stats; checkMs: Stats; peakRssMb: Stats; eventsPerSecond: Stats };
  conditions: string;
  meta: Meta;
}

function runtimeTable(root: string): string {
  const f = read<RuntimeFile>(root, 'results/runtime/runtime.json');
  const rows = f.runs.map((r) => `| ${r.run} | ${n0(r.wallMs)} | ${n0(r.checkMs)} | ${r.peakRssMb} | ${n0(r.eventsPerSecond)} | ${r.findings} | ${r.freeRamGbBefore.toFixed(2)} |`);
  const s = f.summary;
  const med = (x: Stats) => `${n0(x.median)} (${n0(x.min)} to ${n0(x.max)})`;
  return [
    '### Runtime of `eqg check-stream`',
    '',
    `${n0(f.events)} synthetic events from ${n0(f.users)} users, ${(f.fileBytes / 2 ** 20).toFixed(0)} MiB of JSONL, ${f.runs.length} runs, each a fresh process. Machine: ${f.meta.cpu}, ${f.meta.logicalCpus} logical CPUs, ${f.meta.totalRamGb} GB RAM, ${f.meta.os}, Node ${f.meta.node}. ${f.conditions}`,
    '',
    '| run | wall time (ms) | check time (ms) | peak memory (MB) | events per second | findings | free RAM before (GB) |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    `| median (range) | ${med(s.wallMs)} | ${med(s.checkMs)} | ${med(s.peakRssMb)} | ${med(s.eventsPerSecond)} | | |`,
    '',
    `Source: \`results/runtime/runtime.json\`, run at commit \`${short(f.meta)}\`.`,
  ].join('\n');
}

interface MutationFile {
  mutants: number;
  killed: number;
  survived: number;
  notRun: number;
  outcomes: Array<{ id: string; file: string; defect: string; status: string }>;
  meta: Meta;
}

function mutationTable(root: string): string {
  const f = read<MutationFile>(root, 'results/mutation-check.json');
  const rows = f.outcomes.map((o) => `| ${o.id} | \`${o.file}\` | ${o.defect} | ${o.status} |`);
  return [
    '### Mutation check',
    '',
    `${f.killed} of ${f.mutants} injected defects were caught by the tests; ${f.survived} survived and ${f.notRun} could not be applied. Each defect is put into a copy of the code, one at a time, and the tests are run against the copy: first the test files nearest the changed file, then the whole suite before a defect is called a survivor.`,
    '',
    '<details><summary>All defects</summary>',
    '',
    '| id | file | defect | outcome |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
    '</details>',
    '',
    `Source: \`results/mutation-check.json\`, run at commit \`${short(f.meta)}\`.`,
  ].join('\n');
}

export function renderAll(root: string): string {
  const parts = [coverageTable(root), faultTables(root), runtimeTable(root)];
  if (existsSync(join(root, 'results', 'mutation-check.json'))) parts.push(mutationTable(root));
  return parts.join('\n\n');
}

export function spliceReadme(readme: string, body: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('README.md has no results markers');
  return `${readme.slice(0, a)}${START}\n\n${body}\n\n${readme.slice(b)}`;
}

function main(): number {
  const root = repoRoot();
  const body = renderAll(root);
  const tablesPath = join(root, 'results', 'TABLES.md');
  const readmePath = join(root, 'README.md');
  const tables = `${body}\n`;
  const readme = spliceReadme(readFileSync(readmePath, 'utf8'), body);
  if (process.argv[2] === '--check') {
    const stale: string[] = [];
    if (!existsSync(tablesPath) || readFileSync(tablesPath, 'utf8') !== tables) stale.push('results/TABLES.md');
    if (readFileSync(readmePath, 'utf8') !== readme) stale.push('README.md');
    if (stale.length > 0) {
      console.log(`out of date with the result files: ${stale.join(', ')}`);
      return 1;
    }
    console.log('README.md and results/TABLES.md match the result files');
    return 0;
  }
  writeFileSync(tablesPath, tables, 'utf8');
  writeFileSync(readmePath, readme, 'utf8');
  console.log('wrote results/TABLES.md and the results region of README.md');
  return 0;
}

if (isMain(import.meta.url)) process.exitCode = main();
